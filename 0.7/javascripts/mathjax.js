// MathJax setup for pymdownx.arithmatex (generic mode), re-typesetting on
// Material's instant navigation.
window.MathJax = {
  loader: { load: ["[tex]/boldsymbol"] },  // \boldsymbol, for vectors
  tex: {
    packages: { "[+]": ["boldsymbol"] },
    inlineMath: [["\\(", "\\)"]],
    displayMath: [["\\[", "\\]"]],
    processEscapes: true,
    processEnvironments: true,
  },
  options: {
    ignoreHtmlClass: ".*|",
    processHtmlClass: "arithmatex",
  },
};

document$.subscribe(() => {
  MathJax.startup.output.clearCache();
  MathJax.typesetClear();
  MathJax.texReset();
  MathJax.typesetPromise();
});
